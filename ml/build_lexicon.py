"""Builds lib/core/matching/bilingual_lexicon.dart: Bangla words with their
English meanings, so a pack or cover written in one language names a product
saved in the other (`পদার্থবিজ্ঞান` -> physics, `চিনি` -> sugar).

Source: English Wiktionary's Bengali entries, as extracted by wiktextract
(https://kaikki.org/dictionary/Bengali/), CC BY-SA 4.0. Only single-word
English meanings are kept; verb inflections and other "form of" senses are
skipped.

    python -I ml/build_lexicon.py --jsonl G:/Easy_sell/ml_data/dict_download/bengali.jsonl
"""
import argparse
import json
import re
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "lib" / "core" / "matching" / "bilingual_lexicon.dart"
KEEP_POS = {"noun", "adj", "name", "num", "adv", "pron"}
MAX_MEANINGS = 4
# Meanings so general they would join unrelated products.
VAGUE = {
    "thing", "object", "kind", "type", "sort", "one", "person", "man", "woman", "part",
    "place", "name", "something", "someone", "state", "act", "piece", "item", "form", "way",
}


def meanings(gloss: str):
    gloss = re.sub(r"\([^)]*\)", " ", gloss)
    for part in re.split(r"[,;/]| or ", gloss):
        w = part.strip().lower()
        w = re.sub(r"^(a|an|the|to)\s+", "", w)
        if re.fullmatch(r"[a-z][a-z-]+", w) and w not in VAGUE:
            yield w


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jsonl", type=Path, required=True)
    a = ap.parse_args()
    lex: dict[str, list[str]] = {}
    with open(a.jsonl, encoding="utf-8") as f:
        for line in f:
            e = json.loads(line)
            if e.get("pos") not in KEEP_POS:
                continue
            word = unicodedata.normalize("NFC", e.get("word", "").strip())
            if not word or " " in word or not re.search("[\u0980-\u09ff]", word):
                continue
            got = lex.setdefault(word, [])
            for s in e.get("senses", []):
                if "form-of" in s.get("tags", []) or s.get("form_of"):
                    continue
                for g in s.get("glosses", [])[:1]:
                    for m in meanings(g):
                        if m not in got and len(got) < MAX_MEANINGS:
                            got.append(m)
    lex = {w: m for w, m in sorted(lex.items()) if m}
    lines = [
        "// GENERATED by ml/build_lexicon.py -- do not edit by hand.",
        "//",
        "// Bangla words and their English meanings, from English Wiktionary's",
        "// Bengali entries (https://kaikki.org/dictionary/Bengali/), licensed",
        "// CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/).",
        "// ignore_for_file: lines_longer_than_80_chars",
        "library;",
        "",
        "const banglaMeanings = <String, List<String>>{",
    ]
    for w, m in lex.items():
        lines.append(f"  '{w}': [{', '.join(repr(x) for x in m)}],")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lex)} Bangla words, {sum(len(m) for m in lex.values())} meanings -> {OUT} "
          f"({OUT.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
